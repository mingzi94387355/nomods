#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""nomods generator (NeoForge 1.21.1).

Generates a whole family of deliberately useless mods:

    nomods1, nomods2, nomods3, ...

Every generated mod only registers ONE empty, optional network channel
(payload type "<modid>:empty", protocol version "1") and does nothing else:
the payload never gets sent and its handler is empty.

Usage
-----
    python generate.py                    # ensure nomods1 .. nomods10
    python generate.py --count 25         # ensure nomods1 .. nomods25
    python generate.py --start 5 --count 3   # ensure nomods5 .. nomods7
    python generate.py --count 5 --prune  # also delete generated modules > nomods5

The defaults (mod version, NeoForge version, authors, ...) are read from
gradle.properties next to this script; command line options override the
count only.

Generated files are marked with "Generated by generate.py"; hand edits will be
overwritten the next time the generator runs.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent
PROPERTIES_FILE = ROOT / "gradle.properties"
MODULE_RE = re.compile(r"^nomods(\d+)$")
MARKER = "Generated by generate.py"

DEFAULT_COUNT = 10
EMPTY_DESCRIPTION = "An empty mod: no network channel, no payload, no events."
VARIANTS = ("hello", "empty")

DEFAULTS = {
    "mod_version": "1.0.0-neoforge1.21.1",
    "neo_version": "21.1.233",
    "minecraft_version": "1.21.1",
    "minecraft_version_range": "[1.21.1]",
    "loader_version_range": "[1,)",
    "mod_authors": "mingzi_94387355, deepseek",
    "mod_license": "MIT",
    "mod_description": "Registers a network channel, sends one hello packet when a player joins, then does nothing else.",
    "nomods_package_root": "com.chapple",
    "nomods_protocol_version": "1",
}

# --------------------------------------------------------------------------
# Templates
# --------------------------------------------------------------------------

