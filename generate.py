# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------

def load_properties() -> dict[str, str]:
    """Read gradle.properties (key=value) on top of the built-in defaults."""
    values = dict(DEFAULTS)
    if not PROPERTIES_FILE.is_file():
        return values
    for raw in PROPERTIES_FILE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("!") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def module_dirs_on_disk() -> dict[int, Path]:
    found: dict[int, Path] = {}
    for entry in ROOT.iterdir():
        if not entry.is_dir():
            continue
        match = MODULE_RE.match(entry.name)
        if match:
            found[int(match.group(1))] = entry
    return found


def is_generated(module_dir: Path) -> bool:
    build_file = module_dir / "build.gradle"
    try:
        return MARKER in build_file.read_text(encoding="utf-8")[:500]
    except OSError:
        return False


def toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_if_changed(path: Path, content: str) -> bool:
    """Write content with LF line endings; returns True when the file changed."""
    if path.is_file():
        try:
            if path.read_text(encoding="utf-8") == content:
                return False
        except OSError:
            pass
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    return True


def render_module(index: int, props: dict[str, str], variant: str = "hello") -> dict[Path, str]:
    if variant not in VARIANTS:
        raise ValueError(f"unknown variant: {variant}")

    mod_id = f"nomods{index}"
    class_name = f"NoMods{index}"
    package = f"{props['nomods_package_root']}.{mod_id}"
    package_path = Path(*package.split("."))
    description = props["mod_description"] if variant == "hello" else EMPTY_DESCRIPTION

    files: dict[Path, str] = {
        Path("build.gradle"): BUILD_GRADLE.substitute(),
    }

    if variant == "hello":
        files[Path("src/main/java") / package_path / f"{class_name}.java"] = MAIN_JAVA.substitute(
            package=package,
            mod_id=mod_id,
            **{"class": class_name},
            protocol_version=props["nomods_protocol_version"],
        )
        files[Path("src/main/java") / package_path / "HelloPayload.java"] = PAYLOAD_JAVA.substitute(
            package=package,
            **{"class": class_name},
        )
    else:
        files[Path("src/main/java") / package_path / f"{class_name}.java"] = EMPTY_MAIN_JAVA.substitute(
            package=package,
            mod_id=mod_id,
            **{"class": class_name},
        )

    files[Path("src/main/resources/META-INF/neoforge.mods.toml")] = MODS_TOML.substitute(
        loader_version_range=props["loader_version_range"],
        license=toml_escape(props["mod_license"]),
        mod_id=mod_id,
        mod_version=toml_escape(props["mod_version"]),
        mod_name=mod_id,
        authors=toml_escape(props["mod_authors"]),
        description=description,
        neo_version=props["neo_version"],
        minecraft_version_range=props["minecraft_version_range"],
    )
    return files


def write_module(index: int, props: dict[str, str]) -> bool:
    module_dir = ROOT / f"nomods{index}"
    # Older versions used EmptyPayload; remove it so it does not linger in the jar.
    package_path = Path(*f"{props['nomods_package_root']}.nomods{index}".split("."))
    obsolete = module_dir / "src/main/java" / package_path / "EmptyPayload.java"
    if obsolete.is_file():
        obsolete.unlink()
    changes = 0
    for relative, content in render_module(index, props).items():
        if write_if_changed(module_dir / relative, content):
            changes += 1
    return changes > 0


def write_settings(indices: list[int]) -> bool:
    includes = "\n".join(f"include 'nomods{i}'" for i in indices)
    return write_if_changed(ROOT / "settings.gradle", SETTINGS_GRADLE.substitute(includes=includes))


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate no-op NeoForge mods (nomods1, nomods2, ...).",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--count", type=int, default=DEFAULT_COUNT,
                        help="how many mods to ensure, starting at --start")
    parser.add_argument("--start", type=int, default=1,
                        help="index of the first mod to generate")
    parser.add_argument("--prune", action="store_true",
                        help="delete generated nomodsN modules outside the requested range")
    parser.add_argument("--dry-run", action="store_true",
                        help="print what would happen without touching any file")
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.count < 0:
        print("error: --count must be >= 0", file=sys.stderr)
        return 2
    if args.start < 1:
        print("error: --start must be >= 1", file=sys.stderr)
        return 2

    props = load_properties()
    requested = list(range(args.start, args.start + args.count))
    requested_set = set(requested)
    on_disk = module_dirs_on_disk()

    pruned: list[int] = []
    if args.prune:
        for index, path in sorted(on_disk.items()):
            if index in requested_set or not is_generated(path):
                continue
            pruned.append(index)
            if not args.dry_run:
                shutil.rmtree(path)

    remaining = {i: p for i, p in on_disk.items() if i not in pruned}
    for index in requested:
        if index in remaining and not is_generated(remaining[index]):
            print(f"error: {remaining[index].name} exists but was not generated by this tool; "
                  f"move it away or pick another range", file=sys.stderr)
            return 1

    changed_modules: list[int] = []
    if not args.dry_run:
        for index in requested:
            if write_module(index, props):
                changed_modules.append(index)

    all_indices = sorted(set(remaining) | requested_set)
    settings_changed = False
    if not args.dry_run:
        settings_changed = write_settings(all_indices)

    # Report
    created = [i for i in requested if i not in on_disk]
    updated = [i for i in changed_modules if i in on_disk]
    label = "would create" if args.dry_run else "created"
    if created:
        print(f"{label}: " + ", ".join(f"nomods{i}" for i in created))
    if updated:
        print(("would update" if args.dry_run else "updated") + ": " +
              ", ".join(f"nomods{i}" for i in updated))
    if pruned:
        print(("would prune" if args.dry_run else "pruned") + ": " +
              ", ".join(f"nomods{i}" for i in pruned))
    if settings_changed:
        print("updated: settings.gradle")
    if not (created or updated or pruned or settings_changed):
        print("nothing to do - all requested modules are up to date")

    print(f"modules in this build ({len(all_indices)}): " +
          ", ".join(f"nomods{i}" for i in all_indices))
    print()
    print("next steps:")
    print("  .\\build.ps1          # build every module and collect the jars into dist\\")
    print("  .\\gradlew.bat build  # plain Gradle build (put a JDK 21 on JAVA_HOME)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
